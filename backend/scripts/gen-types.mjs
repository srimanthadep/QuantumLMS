// Regenerates frontend/src/lib/database.types.ts from the live schema (run after every migration).
//   SUPABASE_ACCESS_TOKEN=... node backend/scripts/gen-types.mjs
import { writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { management } from "./lib.mjs"

const OUT = fileURLToPath(new URL("../../frontend/src/lib/database.types.ts", import.meta.url))
const { types } = await management("/types/typescript?included_schemas=public")
writeFileSync(OUT, `// Generated by backend/scripts/gen-types.mjs from the Supabase schema. Do not edit by hand.\n${types.trimEnd()}\n`)
console.log(`wrote ${OUT} (${types.length} chars)`)
