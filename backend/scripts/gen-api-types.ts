// Writes frontend/src/lib/api.types.ts from the Drizzle schema: one row type per table, in the JSON shape the API
// sends (timestamps as ISO strings). Run after changing src/db/schema.ts:
//   npm run gen:types
import { writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { getTableConfig, PgTable, type PgColumn } from "drizzle-orm/pg-core"
import * as schema from "../src/db/schema.js"

function tsType(c: PgColumn): string {
  const t = c.columnType
  const base =
    t === "PgArray" ? `${tsType((c as unknown as { baseColumn: PgColumn }).baseColumn)}[]`
    : t === "PgText" || t === "PgUUID" || t === "PgDateString" || t === "PgDate" || t === "PgTimestamp" || t === "PgTimestampString" || t === "PgTime" || t === "PgVarchar" ? "string"
    : t === "PgInteger" || t === "PgSmallInt" || t === "PgBigInt53" || t === "PgNumericNumber" || t === "PgReal" || t === "PgDoublePrecision" || t === "PgSerial" ? "number"
    : t === "PgNumeric" || t === "PgBigInt64" ? "string"
    : t === "PgBoolean" ? "boolean"
    : t === "PgJsonb" || t === "PgJson" ? "Json"
    : "unknown"
  if (base === "unknown") throw new Error(`no TS type for ${c.name} (${t})`)
  return base
}

const tables = (Object.values(schema) as unknown[]).filter((v): v is PgTable => v instanceof PgTable)
const lines: string[] = [
  "// Generated by backend/scripts/gen-api-types.ts from backend/src/db/schema.ts. Don't edit by hand.",
  "// Row shapes as the API sends them: timestamps are ISO strings, dates are YYYY-MM-DD.",
  "",
  "export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]",
  "",
  "export interface Rows {",
]
for (const table of tables.sort((a, b) => getTableConfig(a).name.localeCompare(getTableConfig(b).name))) {
  const cfg = getTableConfig(table)
  if (cfg.name.startsWith("__")) continue
  lines.push(`  ${cfg.name}: {`)
  for (const c of cfg.columns) lines.push(`    ${c.name}: ${tsType(c)}${c.notNull ? "" : " | null"}`)
  lines.push("  }")
}
lines.push(
  "}",
  "",
  "/** One table's row. */",
  "export type Tables<T extends keyof Rows> = Rows[T]",
  "",
  "/** The student profile the API returns: student details plus the account's name, email and photo. */",
  'export type StudentProfile = Rows["profiles"] & Pick<Rows["users"], "email" | "full_name" | "avatar_url" | "is_demo"> & { created_at: string; updated_at: string }',
  "",
)
const out = fileURLToPath(new URL("../../frontend/src/lib/api.types.ts", import.meta.url))
writeFileSync(out, lines.join("\n"))
console.log(`wrote ${tables.length} table types to frontend/src/lib/api.types.ts`)
