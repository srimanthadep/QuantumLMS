import React, { useState, useEffect } from "react"
import { useSearchParams } from "react-router-dom"
import { motion, AnimatePresence } from "framer-motion"
import {
  Sparkles,
  ShieldCheck,
  Lock,
  Mail,
  User,
  Phone,
  Eye,
  EyeOff,
  ArrowRight,
  CheckCircle2,
  AlertCircle,
  GraduationCap,
  Layers,
  LifeBuoy,
  Key,
  Zap,
  RotateCcw,
  ArrowLeft,
  BookOpen,
  Layers3,
  CirclePlay,
} from "lucide-react"
import { demoAccounts, ALL_DEMO_ACCOUNTS } from "@/data/demoAccounts"
import type { UserRole } from "@/types"
import {
  accountConfirmEmail,
  accountForgotPassword,
  accountResendCode,
  accountResetPassword,
  accountSignIn,
  accountVerifyCode,
  cancelAccountSignIn,
  studentSignUp,
  usesAccounts,
  type AccountStep,
} from "./accountAuth"

/** Code verification steps: authenticator MFA, email signup confirmation, or password reset */
type CodeStep = "mfa" | "confirm" | "reset"

const CODE_COPY: Record<
  CodeStep,
  {
    title: string
    subtitle: string
    placeholder: string
    submit: string
  }
> = {
  mfa: {
    title: "Two-Factor Authentication",
    subtitle:
      "Enter the 6-digit security code generated by your authenticator app.",
    placeholder: "000000",
    submit: "Verify & Enter Portal →",
  },
  confirm: {
    title: "Confirm Your Email",
    subtitle:
      "We emailed a verification code. Enter it below to activate your account.",
    placeholder: "Enter confirmation code",
    submit: "Confirm & Launch Portal →",
  },
  reset: {
    title: "Create New Password",
    subtitle:
      "Enter the reset code sent to your email and choose a strong password.",
    placeholder: "Reset code",
    submit: "Update Password & Sign In →",
  },
}

const ROLE_ICONS: Record<UserRole, React.ElementType> = {
  Student: GraduationCap,
  Teacher: Sparkles,
  Evaluator: Layers,
  Support: LifeBuoy,
  Admin: ShieldCheck,
  "Super Admin": Key,
}

interface AuthPageProps {
  onLogin: (user: {
    id?: string
    name: string
    role: UserRole
    email: string
    avatar?: string
    title?: string
  }) => void
  /** @deprecated replaced by theme tokens */
  hexColor?: string
  /** @deprecated replaced by theme tokens */
  onChangeHexColor?: (color: string) => void
}

export default function AuthPage({ onLogin }: AuthPageProps) {
  const [searchParams] = useSearchParams()
  const initialMode =
    searchParams.get("mode") === "signup" ? "signup" : "signin"
  const paramRole = searchParams.get("role") as UserRole | null
  const defaultAccount =
    demoAccounts.find((d) => d.role === (paramRole || "Student")) ??
    demoAccounts[3]

  const [mode, setMode] = useState<"signin" | "signup">(initialMode)
  const [role, setRole] = useState<UserRole>(defaultAccount.role)
  const [email, setEmail] = useState(
    initialMode === "signin" ? defaultAccount.email : "",
  )
  const [password, setPassword] = useState(
    initialMode === "signin" ? defaultAccount.password : "",
  )
  const [fullName, setFullName] = useState(
    initialMode === "signin" ? defaultAccount.name : "",
  )
  const [phone, setPhone] = useState("")
  const [showPassword, setShowPassword] = useState(false)
  const [isLoading, setIsLoading] = useState(false)
  const [infoMessage, setInfoMessage] = useState<string | null>(null)
  const [errorMessage, setErrorMessage] = useState<string | null>(null)

  // Verification code challenge step
  const [codeStep, setCodeStep] = useState<CodeStep | null>(null)
  const [code, setCode] = useState("")
  const [newPassword, setNewPassword] = useState("")

  // Update mode or handle OAuth / Cognito callback params
  useEffect(() => {
    if (searchParams.get("mode") === "signup") {
      setMode("signup")
    }

    const errorParam = searchParams.get("error")
    if (errorParam) {
      setErrorMessage(decodeURIComponent(errorParam))
    }

    const authSuccess = searchParams.get("auth_success")
    const accessTokenParam = searchParams.get("access_token")
    if (authSuccess || accessTokenParam) {
      setIsLoading(true)
      fetch("/api/me", {
        headers: accessTokenParam
          ? { Authorization: `Bearer ${accessTokenParam}` }
          : {},
      })
        .then((res) => (res.ok ? res.json() : null))
        .then((user) => {
          if (user) {
            onLogin({
              id: user.id,
              name: user.full_name || "Learner",
              role: user.role || "Student",
              email: user.email,
              avatar: user.avatar_url ?? undefined,
            })
          }
        })
        .catch(() => undefined)
        .finally(() => setIsLoading(false))
    }
  }, [searchParams, onLogin])

  const handleRoleSelect = (targetRole: UserRole) => {
    setRole(targetRole)
    setErrorMessage(null)
    setInfoMessage(null)
    if (codeStep) {
      setCodeStep(null)
      void cancelAccountSignIn()
    }
    const account = demoAccounts.find((d) => d.role === targetRole) || ALL_DEMO_ACCOUNTS[targetRole]
    if (account) {
      setEmail(account.email)
      setPassword(account.password)
      setFullName(account.name)
    }
  }

  /** Runs an async Cognito/API auth step and handles completion */
  const runAccount = async (
    step: () => Promise<AccountStep>,
    fallbackDemoRole?: UserRole,
  ) => {
    setIsLoading(true)
    setErrorMessage(null)
    try {
      const result = await step()
      if (result === "mfa" || result === "confirm") {
        setCodeStep(result)
        setCode("")
        if (result === "confirm") {
          setInfoMessage(
            `A verification code was dispatched to ${email.trim()}.`,
          )
        }
        return
      }
      setCodeStep(null)
      setInfoMessage(null)
      onLogin(result)
    } catch (e) {
      if (fallbackDemoRole) {
        const account = ALL_DEMO_ACCOUNTS[fallbackDemoRole] || demoAccounts.find((d) => d.role === fallbackDemoRole)
        if (account) {
          onLogin({
            id: account.role.toLowerCase(),
            name: account.name,
            role: account.role,
            email: account.email,
            avatar: account.avatar,
            title: account.title,
          })
          return
        }
      }
      setErrorMessage(
        (e as Error).message ||
          "Authentication failed. Please check your credentials.",
      )
    } finally {
      setIsLoading(false)
    }
  }

  /** Direct 1-click launch for a demo account */
  const handleQuickLaunch = (targetRole: UserRole) => {
    const account = demoAccounts.find((d) => d.role === targetRole) || ALL_DEMO_ACCOUNTS[targetRole]
    if (!account) return

    setRole(targetRole)
    setEmail(account.email)
    setPassword(account.password)
    setFullName(account.name)
    setErrorMessage(null)
    setInfoMessage(null)

    if (usesAccounts(targetRole)) {
      void runAccount(
        () => accountSignIn(account.email, account.password),
        targetRole,
      )
      return
    }

    onLogin({
      id: account.role.toLowerCase(),
      name: account.name,
      role: account.role,
      email: account.email,
      avatar: account.avatar,
      title: account.title,
    })
  }

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault()
    setErrorMessage(null)

    if (codeStep === "mfa") {
      void runAccount(() => accountVerifyCode(code))
      return
    }

    if (codeStep === "confirm") {
      void runAccount(() => accountConfirmEmail(email, code, password))
      return
    }

    if (codeStep === "reset") {
      void runAccount(async () => {
        await accountResetPassword(email, code, newPassword)
        setPassword(newPassword)
        return accountSignIn(email, newPassword)
      })
      return
    }

    if (mode === "signin") {
      const trimmedEmail = email.trim().toLowerCase()
      const matchedDemo =
        demoAccounts.find((d) => d.email.toLowerCase() === trimmedEmail) ||
        Object.values(ALL_DEMO_ACCOUNTS).find((d) => d.email.toLowerCase() === trimmedEmail)
      const effectiveRole = matchedDemo ? matchedDemo.role : role

      if (!usesAccounts(effectiveRole) && matchedDemo) {
        onLogin({
          id: matchedDemo.role.toLowerCase(),
          name: matchedDemo.name,
          role: matchedDemo.role,
          email: matchedDemo.email,
          avatar: matchedDemo.avatar,
          title: matchedDemo.title,
        })
        return
      }

      void runAccount(
        () => accountSignIn(email, password),
        effectiveRole,
      )
      return
    }

    // Sign up mode (creates a Student account by default)
    void runAccount(() => studentSignUp(fullName, email, password))
  }

  const handleForgotPassword = async () => {
    if (!email.trim()) {
      setErrorMessage(
        "Please enter your email address first, then click Forgot.",
      )
      return
    }
    setIsLoading(true)
    setErrorMessage(null)
    try {
      await accountForgotPassword(email)
      setCodeStep("reset")
      setCode("")
      setNewPassword("")
      setInfoMessage(
        `If an account exists for ${email.trim()}, a password reset code was sent.`,
      )
    } catch (e) {
      setErrorMessage(
        (e as Error).message || "The password reset code could not be sent.",
      )
    } finally {
      setIsLoading(false)
    }
  }

  const handleResendCode = async () => {
    setErrorMessage(null)
    try {
      if (codeStep === "reset") {
        await accountForgotPassword(email)
      } else {
        await accountResendCode(email)
      }
      setInfoMessage(`A fresh security code was sent to ${email.trim()}.`)
    } catch (e) {
      setErrorMessage(
        (e as Error).message || "Unable to resend code. Please try again.",
      )
    }
  }

  const inputClass =
    "h-10 w-full rounded-xl border border-[#e4e5eb] bg-white px-4 text-[13.5px] text-[#171923] outline-none transition placeholder:text-[#a0a2ad] focus:border-[#6658e8] focus:ring-4 focus:ring-[#6658e8]/10"
  const labelClass =
    "mb-1.5 block text-[12px] font-semibold tracking-[0.01em] text-[#454755]"

  return (
    <main className="auth-page min-h-dvh bg-[#f6f6f8] text-[#171923] selection:bg-[#dedbff] selection:text-[#3024a8]">
      <div className="mx-auto grid min-h-dvh w-full max-w-[1440px] grid-cols-1 lg:grid-cols-[1.02fr_0.98fr]">
        <section className="relative hidden overflow-hidden bg-[#17182d] px-10 py-6 text-white lg:flex lg:flex-col xl:px-16">
          <div
            className="pointer-events-none absolute inset-0"
            aria-hidden="true"
          >
            <div className="absolute -left-40 top-12 h-[520px] w-[520px] rounded-full border border-white/[0.07]" />
            <div className="absolute -left-20 top-32 h-[360px] w-[360px] rounded-full border border-white/[0.09]" />
            <div className="absolute left-20 top-52 h-[180px] w-[180px] rounded-full border border-white/[0.12]" />
            <div className="absolute -right-32 -top-40 h-[520px] w-[520px] rounded-full bg-[#6257d9]/25 blur-[100px]" />
            <div className="absolute -bottom-48 -left-28 h-[420px] w-[420px] rounded-full bg-[#396c9f]/20 blur-[100px]" />
            <div className="absolute inset-0 opacity-[0.16] [background-image:linear-gradient(rgba(255,255,255,.08)_1px,transparent_1px),linear-gradient(90deg,rgba(255,255,255,.08)_1px,transparent_1px)] [background-size:64px_64px] [mask-image:linear-gradient(to_bottom,black,transparent_82%)]" />
          </div>
          <div className="relative z-10 flex items-center gap-3">
            <img
              src="/assets/logo.png"
              alt=""
              className="h-10 w-auto object-contain"
            />
            <div className="leading-tight">
              <div className="text-[15px] font-semibold tracking-tight">
                Quantum
              </div>
              <div className="mt-1 text-[9px] font-semibold uppercase tracking-[0.22em] text-white/55">
                School of AI
              </div>
            </div>
          </div>
          <div className="relative z-10 my-auto max-w-[560px] py-8">
            <div className="mb-5 inline-flex items-center gap-2 rounded-full border border-white/10 bg-white/[0.06] px-3.5 py-2 text-[11px] font-medium tracking-wide text-white/75 backdrop-blur">
              <span className="h-1.5 w-1.5 rounded-full bg-[#a99fff]" />
              YOUR LEARNING SPACE
            </div>
            <h1 className="max-w-[520px] text-[40px] font-medium leading-[1.08] tracking-[-0.045em] xl:text-[50px]">
              Learn with focus.{" "}
              <span className="text-[#a99fff]">Build what’s next.</span>
            </h1>
            <p className="mt-4 max-w-[420px] text-[14px] leading-6 text-white/60">
              Your courses, live sessions, and progress — together in one place.
            </p>
            <div className="auth-learning-preview mt-9 max-w-[490px] rounded-2xl border border-white/10 bg-white/[0.055] p-4 shadow-2xl shadow-black/10 backdrop-blur-sm">
              <div className="mb-3 flex items-center justify-between">
                <div>
                  <p className="text-[10px] font-semibold uppercase tracking-[0.19em] text-white/45">
                    A clear path forward
                  </p>
                  <p className="mt-1 text-sm font-medium text-white/90">
                    Your learning, in rhythm
                  </p>
                </div>
                <div className="flex h-9 w-9 items-center justify-center rounded-xl border border-white/10 bg-white/[0.07] text-[#b5adff]">
                  <Layers3 className="h-[17px] w-[17px]" strokeWidth={1.7} />
                </div>
              </div>
              <div className="space-y-3">
                <div className="flex items-center gap-3 rounded-xl border border-white/[0.06] bg-[#111225]/70 px-3.5 py-3">
                  <span className="flex h-8 w-8 items-center justify-center rounded-lg bg-[#8176f2]/15 text-[#b9b1ff]">
                    <BookOpen className="h-4 w-4" strokeWidth={1.7} />
                  </span>
                  <span className="flex-1 text-[12px] font-medium text-white/85">
                    Pick up where you left off
                  </span>
                  <ArrowRight className="h-3.5 w-3.5 text-white/35" />
                </div>
                <div className="flex items-center gap-3 rounded-xl border border-white/[0.06] bg-[#111225]/70 px-3.5 py-3">
                  <span className="flex h-8 w-8 items-center justify-center rounded-lg bg-[#56a9c5]/15 text-[#87d0e3]">
                    <CirclePlay className="h-4 w-4" strokeWidth={1.7} />
                  </span>
                  <span className="flex-1 text-[12px] font-medium text-white/85">
                    Join your next live session
                  </span>
                  <span className="h-1.5 w-1.5 rounded-full bg-[#8de0bd]" />
                </div>
              </div>
              <div className="mt-3 flex items-center gap-1.5">
                <span className="h-1 flex-1 rounded-full bg-[#8b80f3]" />
                <span className="h-1 flex-1 rounded-full bg-white/20" />
                <span className="h-1 flex-1 rounded-full bg-white/10" />
                <span className="h-1 flex-1 rounded-full bg-white/10" />
                <span className="ml-2 text-[10px] text-white/45">
                  Your pace, your progress
                </span>
              </div>
            </div>
          </div>
          <div className="relative z-10 flex items-center justify-between text-[10px] text-white/40">
            <span>© {new Date().getFullYear()} Quantum School of AI</span>
            <span className="flex items-center gap-2">
              <ShieldCheck className="h-3.5 w-3.5" />
              Secure access
            </span>
          </div>
        </section>

        <section className="flex min-h-dvh flex-col bg-[#f6f6f8] px-5 py-4 sm:px-10 lg:px-12 lg:py-5 xl:px-16">
          <header className="flex items-center justify-between lg:justify-end">
            <div className="flex items-center gap-2.5 lg:hidden">
              <img
                src="/assets/logo.png"
                alt=""
                className="h-7 w-auto object-contain"
              />
              <span className="text-sm font-semibold tracking-tight">
                Quantum{" "}
                <span className="font-normal text-[#777987]">School of AI</span>
              </span>
            </div>
            {!codeStep && (
              <p className="text-[12px] text-[#777987]">
                {mode === "signin"
                  ? "New to Quantum?"
                  : "Already have an account?"}{" "}
                <button
                  type="button"
                  onClick={() => {
                    const nextMode = mode === "signin" ? "signup" : "signin"
                    setMode(nextMode)
                    setErrorMessage(null)
                    setInfoMessage(null)
                    if (nextMode === "signup") {
                      setRole("Student")
                      setEmail("")
                      setPassword("")
                      setFullName("")
                      setPhone("")
                    } else {
                      const acc =
                        demoAccounts.find((d) => d.role === role) ??
                        demoAccounts[3]
                      setEmail(acc.email)
                      setPassword(acc.password)
                      setFullName(acc.name)
                    }
                  }}
                  className="font-semibold text-[#5749d2] transition hover:text-[#3930a5]"
                >
                  {mode === "signin" ? "Create account" : "Sign in"}
                </button>
              </p>
            )}
          </header>
          <div className="mx-auto flex w-full max-w-[440px] flex-1 flex-col justify-center py-3">
            <div className="mb-4">
              <div className="mb-3 flex h-9 w-9 items-center justify-center rounded-[12px] border border-[#e5e2ff] bg-[#eeecff] text-[#5749d2]">
                {codeStep ? (
                  <ShieldCheck className="h-5 w-5" strokeWidth={1.8} />
                ) : (
                  <span className="text-[18px] font-semibold tracking-[-0.08em]">
                    Q<span className="text-[#8d82ed]">.</span>
                  </span>
                )}
              </div>
              <h2 className="text-[26px] font-semibold leading-tight tracking-[-0.04em] text-[#171923] sm:text-[30px]">
                {codeStep
                  ? CODE_COPY[codeStep].title
                  : mode === "signin"
                    ? "Welcome back"
                    : "Create your account"}
              </h2>
              <p className="mt-1 text-[12px] leading-5 text-[#777987]">
                {codeStep
                  ? CODE_COPY[codeStep].subtitle
                  : mode === "signin"
                    ? "Sign in with your academy account or launch a demo portal."
                    : "Start your learning journey with Quantum."}
              </p>
            </div>

            {/* 1-Click Instant Demo Portals */}
            {!codeStep && mode === "signin" && (
              <div className="mb-4">
                <div className="mb-2 flex items-center justify-between">
                  <span className="flex items-center gap-1.5 text-[10.5px] font-bold uppercase tracking-wider text-[#626472]">
                    <Zap className="h-3.5 w-3.5 fill-amber-500 text-amber-500" />
                    <span>Instant 1-Click Demo Portals</span>
                  </span>
                  <span className="rounded-full bg-[#eeecff] px-2 py-0.5 text-[10px] font-semibold text-[#5749d2]">
                    Sandbox Mode
                  </span>
                </div>

                <div className="grid grid-cols-2 gap-2.5">
                  {demoAccounts.map((acc) => {
                    const RoleIcon = ROLE_ICONS[acc.role]
                    const isSelected = role === acc.role

                    return (
                      <div
                        key={acc.role}
                        role="button"
                        tabIndex={0}
                        onClick={() => handleRoleSelect(acc.role)}
                        onKeyDown={(e) => {
                          if (e.key === "Enter" || e.key === " ") {
                            e.preventDefault()
                            handleRoleSelect(acc.role)
                          }
                        }}
                        className={`group relative flex cursor-pointer flex-col justify-between rounded-xl border p-2.5 text-left transition-all ${
                          isSelected
                            ? "border-[#5749d2] bg-[#eeecff]/60 shadow-xs ring-2 ring-[#5749d2]/15"
                            : "border-[#e4e5eb] bg-white hover:border-[#c8cad6] hover:bg-white/90"
                        }`}
                      >
                        <div className="flex w-full items-start justify-between gap-1">
                          <div
                            className="flex h-6 w-6 shrink-0 items-center justify-center rounded-md text-xs font-bold"
                            style={{
                              backgroundColor: `${acc.accentColor}18`,
                              color: acc.accentColor,
                            }}
                          >
                            <RoleIcon className="h-3.5 w-3.5" />
                          </div>
                          <span
                            className="truncate rounded px-1.5 py-0.5 text-[8px] font-bold uppercase tracking-wider"
                            style={{
                              backgroundColor: `${acc.accentColor}15`,
                              color: acc.accentColor,
                            }}
                          >
                            {acc.badge}
                          </span>
                        </div>

                        <div className="mt-1.5 min-w-0">
                          <div className="truncate text-[12px] font-bold text-[#171923]">
                            {acc.role}
                          </div>
                          <div className="truncate text-[10px] text-[#777987]">
                            {acc.name}
                          </div>
                        </div>

                        <button
                          type="button"
                          disabled={isLoading}
                          onClick={(e) => {
                            e.stopPropagation()
                            handleQuickLaunch(acc.role)
                          }}
                          className="mt-1.5 flex w-full items-center justify-between border-t border-[#e4e5eb]/80 pt-1 text-[10px] font-semibold text-[#5749d2] transition hover:text-[#3930a5] disabled:opacity-50"
                        >
                          <span>Launch</span>
                          <ArrowRight className="h-2.5 w-2.5 transition-transform group-hover:translate-x-0.5" />
                        </button>
                      </div>
                    )
                  })}
                </div>
              </div>
            )}

            <AnimatePresence mode="wait">
              {infoMessage && !errorMessage && (
                <motion.div
                  key="auth-info-alert"
                  initial={{ opacity: 0, y: -4 }}
                  animate={{ opacity: 1, y: 0 }}
                  exit={{ opacity: 0 }}
                  className="mb-3.5 flex items-start gap-2.5 rounded-xl border border-[#d8e9df] bg-[#f0f8f3] p-3 text-[12px] leading-5 text-[#34724d]"
                >
                  <CheckCircle2 className="mt-0.5 h-4 w-4 shrink-0" />
                  <span>{infoMessage}</span>
                </motion.div>
              )}
              {errorMessage && (
                <motion.div
                  key="auth-error-alert"
                  role="alert"
                  initial={{ opacity: 0, y: -4 }}
                  animate={{ opacity: 1, y: 0 }}
                  exit={{ opacity: 0 }}
                  className="mb-3.5 flex items-start gap-2.5 rounded-xl border border-[#f0d8d7] bg-[#fff4f3] p-3 text-[12px] leading-5 text-[#a53a35]"
                >
                  <AlertCircle className="mt-0.5 h-4 w-4 shrink-0" />
                  <span>{errorMessage}</span>
                </motion.div>
              )}
            </AnimatePresence>
            <form onSubmit={handleSubmit} className="space-y-3">
              {codeStep ? (
                <div className="space-y-3">
                  <div>
                    <label htmlFor="auth-code-input" className={labelClass}>
                      {codeStep === "mfa"
                        ? "Authentication code"
                        : "Verification code"}
                    </label>
                    <input
                      id="auth-code-input"
                      type="text"
                      inputMode="numeric"
                      autoComplete="one-time-code"
                      required
                      autoFocus
                      value={code}
                      onChange={(e) => setCode(e.target.value)}
                      placeholder={CODE_COPY[codeStep].placeholder}
                      className={`${inputClass} text-center font-mono tracking-[0.35em]`}
                    />
                  </div>
                  {codeStep === "reset" && (
                    <div>
                      <label htmlFor="auth-new-pw" className={labelClass}>
                        New password
                      </label>
                      <div className="relative">
                        <input
                          id="auth-new-pw"
                          type={showPassword ? "text" : "password"}
                          autoComplete="new-password"
                          required
                          minLength={10}
                          value={newPassword}
                          onChange={(e) => setNewPassword(e.target.value)}
                          placeholder="At least 10 characters"
                          className={`${inputClass} pr-12`}
                        />
                        <button
                          type="button"
                          onClick={() => setShowPassword(!showPassword)}
                          aria-label={
                            showPassword ? "Hide password" : "Show password"
                          }
                          className="absolute inset-y-0 right-0 flex items-center px-4 text-[#898b97] hover:text-[#333544]"
                        >
                          {showPassword ? (
                            <EyeOff className="h-4 w-4" />
                          ) : (
                            <Eye className="h-4 w-4" />
                          )}
                        </button>
                      </div>
                    </div>
                  )}
                  <div className="flex items-center justify-between pt-1 text-[12px]">
                    <button
                      type="button"
                      onClick={() => {
                        setCodeStep(null)
                        setErrorMessage(null)
                        setInfoMessage(null)
                        void cancelAccountSignIn()
                      }}
                      className="flex items-center gap-1.5 text-[#777987] transition hover:text-[#242634]"
                    >
                      <ArrowLeft className="h-3.5 w-3.5" />
                      Back to sign in
                    </button>
                    {codeStep !== "mfa" && (
                      <button
                        type="button"
                        onClick={() => void handleResendCode()}
                        className="font-semibold text-[#5749d2] hover:text-[#3930a5]"
                      >
                        Resend code
                      </button>
                    )}
                  </div>
                </div>
              ) : (
                <>
                  {mode === "signup" && (
                    <>
                      <div>
                        <label htmlFor="auth-name" className={labelClass}>
                          Full name
                        </label>
                        <div className="relative">
                          <User className="absolute left-4 top-1/2 h-4 w-4 -translate-y-1/2 text-[#9b9daa]" />
                          <input
                            id="auth-name"
                            type="text"
                            autoComplete="name"
                            required
                            value={fullName}
                            onChange={(e) => setFullName(e.target.value)}
                            placeholder="Your full name"
                            className={`${inputClass} pl-11`}
                          />
                        </div>
                      </div>
                      <div>
                        <label htmlFor="auth-phone" className={labelClass}>
                          Phone number (with country code)
                        </label>
                        <div className="relative">
                          <Phone className="absolute left-4 top-1/2 h-4 w-4 -translate-y-1/2 text-[#9b9daa]" />
                          <input
                            id="auth-phone"
                            type="tel"
                            autoComplete="tel"
                            value={phone}
                            onChange={(e) => setPhone(e.target.value)}
                            placeholder="+91 98765 43210"
                            className={`${inputClass} pl-11`}
                          />
                        </div>
                      </div>
                    </>
                  )}
                  <div>
                    <label htmlFor="auth-email" className={labelClass}>
                      Email address
                    </label>
                    <div className="relative">
                      <Mail className="absolute left-4 top-1/2 h-4 w-4 -translate-y-1/2 text-[#9b9daa]" />
                      <input
                        id="auth-email"
                        type="email"
                        autoComplete="email"
                        required
                        value={email}
                        onChange={(e) => setEmail(e.target.value)}
                        placeholder="you@example.com"
                        className={`${inputClass} pl-11`}
                      />
                    </div>
                  </div>
                  <div>
                    <div className="mb-1.5 flex items-center justify-between">
                      <label
                        htmlFor="auth-password"
                        className={`${labelClass} mb-0`}
                      >
                        Password
                      </label>
                      {mode === "signin" && (
                        <button
                          type="button"
                          onClick={() => void handleForgotPassword()}
                          className="text-[11px] font-semibold text-[#5749d2] transition hover:text-[#3930a5]"
                        >
                          Forgot password?
                        </button>
                      )}
                    </div>
                    <div className="relative">
                      <Lock className="absolute left-4 top-1/2 h-4 w-4 -translate-y-1/2 text-[#9b9daa]" />
                      <input
                        id="auth-password"
                        type={showPassword ? "text" : "password"}
                        autoComplete={
                          mode === "signin"
                            ? "current-password"
                            : "new-password"
                        }
                        required
                        value={password}
                        onChange={(e) => setPassword(e.target.value)}
                        placeholder="Enter your password"
                        className={`${inputClass} pl-11 pr-12`}
                      />
                      <button
                        type="button"
                        onClick={() => setShowPassword(!showPassword)}
                        aria-label={
                          showPassword ? "Hide password" : "Show password"
                        }
                        className="absolute inset-y-0 right-0 flex items-center px-4 text-[#898b97] transition hover:text-[#333544]"
                      >
                        {showPassword ? (
                          <EyeOff className="h-4 w-4" />
                        ) : (
                          <Eye className="h-4 w-4" />
                        )}
                      </button>
                    </div>
                    {mode === "signup" && (
                      <p className="mt-1.5 text-[11px] leading-5 text-[#858794]">
                        Use at least 10 characters with upper and lower case
                        letters and a number.
                      </p>
                    )}
                  </div>
                </>
              )}
              <button
                type="submit"
                disabled={isLoading}
                className="group mt-1 flex h-10.5 w-full items-center justify-center gap-2 rounded-xl bg-[#5749d2] px-4 text-[13px] font-semibold text-white shadow-[0_7px_18px_rgba(87,73,210,.18)] transition hover:bg-[#493dbb] hover:shadow-[0_9px_22px_rgba(87,73,210,.24)] active:translate-y-px disabled:cursor-not-allowed disabled:opacity-60"
              >
                {isLoading ? (
                  <>
                    <RotateCcw className="h-4 w-4 animate-spin" />
                    <span>One moment…</span>
                  </>
                ) : (
                  <>
                    <span>
                      {codeStep
                        ? CODE_COPY[codeStep].submit.replace(" →", "")
                        : mode === "signin"
                          ? `Sign in as ${role}`
                          : "Create account"}
                    </span>
                    <ArrowRight className="h-4 w-4 transition-transform group-hover:translate-x-0.5" />
                  </>
                )}
              </button>
            </form>

            <p className="auth-security-note mt-3.5 flex items-center justify-center gap-2 text-[10px] text-[#999ba6]">
              <ShieldCheck className="h-3.5 w-3.5" />
              Your account is protected with secure sign-in
            </p>
          </div>
          <footer className="auth-footer flex items-center justify-center gap-2 pb-1 text-[10px] text-[#a0a1ab] lg:justify-end">
            <span>© {new Date().getFullYear()} Quantum School of AI</span>
            <span aria-hidden="true">·</span>
            <span>Learning, made clear</span>
          </footer>
        </section>
      </div>
    </main>
  )
}
